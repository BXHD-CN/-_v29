def evaluate(idx):
    hit1 = hit5 = 0
    for q, expected in REWRITES:
        hits = idx.search(q, k=5, source="term")
        if hits and expected in hits[0]["zh"]: hit1 += 1
        if any(expected in h["zh"] for h in hits): hit5 += 1
    return hit1/len(REWRITES), hit5/len(REWRITES)

